import 'package:localsend_app/model/persistence/sync_share.dart';
import 'package:localsend_app/provider/persistence_provider.dart';
import 'package:refena_flutter/refena_flutter.dart';

/// This provider stores the list of directories the local device shares
/// with the rest of the network. The list is persisted to
/// [PersistenceService] (backed by `shared_preferences`) and forwarded to
/// the HTTP server as part of `ServerConfigV2.sync_shares` at startup.
///
/// Each entry is a [SyncShare]; the [id] is the URL component under
/// `/api/localsend/sync/{id}/*` and the file name of the receiver-side
/// state file, so it is stable for the lifetime of the share.
final syncSharesProvider = ReduxProvider<SyncSharesService, List<SyncShare>>((ref) {
  return SyncSharesService(ref.read(persistenceProvider));
});

class SyncSharesService extends ReduxNotifier<List<SyncShare>> {
  final PersistenceService _persistence;

  SyncSharesService(this._persistence);

  @override
  List<SyncShare> init() => _persistence.getSyncShares();
}

/// Adds a new share. The id is generated by [SyncShare.create] so the
/// caller does not have to worry about uniqueness.
class AddSyncShareAction extends AsyncReduxAction<SyncSharesService, List<SyncShare>> {
  final String name;
  final String root;
  final List<String> excludes;

  AddSyncShareAction({required this.name, required this.root, this.excludes = const []});

  @override
  Future<List<SyncShare>> reduce() async {
    final share = SyncShare.create(name: name, root: root, excludes: excludes);
    final updated = List<SyncShare>.unmodifiable([...state, share]);
    await notifier._persistence.setSyncShares(updated);
    return updated;
  }
}

/// Removes a share by id. The receiver-side state file (`{id}.json`) is
/// intentionally left in place: cleaning it up is the receiver's job
/// because it may still want to consult the last known manifest.
class RemoveSyncShareAction extends AsyncReduxAction<SyncSharesService, List<SyncShare>> {
  final String id;

  RemoveSyncShareAction(this.id);

  @override
  Future<List<SyncShare>> reduce() async {
    final updated = state.where((s) => s.id != id).toList(growable: false);
    if (updated.length == state.length) {
      return state;
    }
    final immutable = List<SyncShare>.unmodifiable(updated);
    await notifier._persistence.setSyncShares(immutable);
    return immutable;
  }
}

/// Updates the name, root or excludes of a share. The id never changes.
class UpdateSyncShareAction extends AsyncReduxAction<SyncSharesService, List<SyncShare>> {
  final String id;
  final String? name;
  final String? root;
  final List<String>? excludes;

  UpdateSyncShareAction({required this.id, this.name, this.root, this.excludes});

  @override
  Future<List<SyncShare>> reduce() async {
    final index = state.indexWhere((s) => s.id == id);
    if (index == -1) {
      return state;
    }
    final next = state[index].copyWith(name: name, root: root, excludes: excludes);
    final updated = List<SyncShare>.unmodifiable(
      <SyncShare>[...state]..[index] = next,
    );
    await notifier._persistence.setSyncShares(updated);
    return updated;
  }
}
